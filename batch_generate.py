#!/usr/bin/env python3
"""Batch generator: spot list (JSON or CSV) -> TexasSolver CLI batch folder.

Usage:
  python3 batch_generate.py SPOT_LIST.json --out BATCH_DIR [--dry-run]
  python3 batch_generate.py SPOT_LIST.csv  --out BATCH_DIR --solver-name TexasSolver --solver-version v0.2.0

Writes (BATCH_DIR must not exist; nothing is ever overwritten):
  BATCH_DIR/manifest.json            normalized spot list + per-spot input hashes
  BATCH_DIR/run_all.bat              Windows runner (CRLF)
  BATCH_DIR/run_all.sh               POSIX runner
  BATCH_DIR/spots/<spot_id>/input.txt  console_solver command file (LF)

--dry-run validates everything and prints every file it WOULD write, writing nothing.
This script never runs the solver and never produces strategy numbers.
"""
import argparse
import datetime
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from retrosolver_pipeline import BATCH_MANIFEST_SCHEMA, PIPELINE_VERSION  # noqa: E402
from retrosolver_pipeline.canonical import canonical_sha256, sha256_hex  # noqa: E402
from retrosolver_pipeline.spotlist import (SOLVER_OUTPUT_FILE, SpotListError,  # noqa: E402
                                           load_spot_list, render_cli_script)

RUN_SH = """#!/bin/sh
# RetroSolver batch runner (generated by batch_generate.py {ver}). Runs console_solver once per spot.
# Usage: sh run_all.sh /path/to/console_solver /path/to/TexasSolver/resources
# Never overwrites: a spot folder that already has any solver output is skipped.
set -u
if [ $# -ne 2 ]; then echo "usage: sh run_all.sh SOLVER_EXE RESOURCE_DIR" >&2; exit 2; fi
SOLVER="$1"; RES="$2"
# TexasSolver v0.2.0 segfaulted (exit 139) on a full-range flop at 7 threads with the default
# OpenMP thread stack; a 64M stack fixed it on the box. Override by exporting OMP_STACKSIZE.
OMP_STACKSIZE="${{OMP_STACKSIZE:-64M}}"; export OMP_STACKSIZE
ROOT="$(cd "$(dirname "$0")" && pwd)"
run_spot() {{
  d="$ROOT/spots/$1"
  for f in {out} solve_stdout.log tmp_log.txt run_started_at.txt; do
    if [ -e "$d/$f" ]; then echo "[skip] $1: $f already exists (move the folder aside to re-run)"; return 0; fi
  done
  echo "[run] $1"
  ( cd "$d" && date -u +%Y-%m-%dT%H:%M:%SZ > run_started_at.txt \\
    && "$SOLVER" -i input.txt -r "$RES" -m holdem > solve_stdout.log 2>&1; echo $? > solver_exit_code.txt; \\
    date -u +%Y-%m-%dT%H:%M:%SZ > run_finished_at.txt )
  echo "[done] $1 exit=$(cat "$d/solver_exit_code.txt")"
}}
{calls}
echo "[batch] finished {n} spot(s)"
"""

RUN_BAT = """@echo off
rem RetroSolver batch runner (generated by batch_generate.py {ver}). Runs console_solver.exe once per spot.
rem Usage: run_all.bat <console_solver.exe> <resources_dir>
rem Never overwrites: a spot folder that already has any solver output is skipped.
setlocal
if "%~2"=="" (echo usage: run_all.bat SOLVER_EXE RESOURCE_DIR & exit /b 2)
set "SOLVER=%~1"
set "RES=%~2"
set "ROOT=%~dp0"
rem TexasSolver v0.2.0 segfaulted on a full-range flop with the default OpenMP thread stack; 64M fixed it.
if not defined OMP_STACKSIZE set "OMP_STACKSIZE=64M"
{calls}
echo [batch] finished {n} spot(s)
exit /b 0

:run_spot
set "D=%ROOT%spots\\%~1"
for %%F in ({out} solve_stdout.log tmp_log.txt run_started_at.txt) do (
  if exist "%D%\\%%F" (echo [skip] %~1: %%F already exists - move the folder aside to re-run & exit /b 0)
)
echo [run] %~1
pushd "%D%"
powershell -NoProfile -Command "(Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')" > run_started_at.txt
"%SOLVER%" -i input.txt -r "%RES%" -m holdem > solve_stdout.log 2>&1
echo %ERRORLEVEL% > solver_exit_code.txt
powershell -NoProfile -Command "(Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')" > run_finished_at.txt
popd
echo [done] %~1
exit /b 0
"""


def build_batch(spot_list, created_at):
    files = {}
    manifest_spots = []
    for spot in spot_list["spots"]:
        script = render_cli_script(spot)
        rel = "spots/%s/input.txt" % spot["spot_id"]
        files[rel] = script.encode("utf-8")
        manifest_spots.append({"spot": spot, "input_file": rel,
                               "input_sha256": sha256_hex(files[rel]),
                               "expected_output_file": "spots/%s/%s" % (spot["spot_id"], SOLVER_OUTPUT_FILE)})
    ids = [s["spot_id"] for s in spot_list["spots"]]
    files["run_all.sh"] = RUN_SH.format(
        ver=PIPELINE_VERSION, out=SOLVER_OUTPUT_FILE, n=len(ids),
        calls="\n".join("run_spot %s" % i for i in ids)).encode("utf-8")
    files["run_all.bat"] = RUN_BAT.format(
        ver=PIPELINE_VERSION, out=SOLVER_OUTPUT_FILE, n=len(ids),
        calls="\n".join("call :run_spot %s" % i for i in ids)).replace("\n", "\r\n").encode("utf-8")
    manifest = {
        "schema": BATCH_MANIFEST_SCHEMA,
        "generator": {"name": "retrosolver batch_generate.py", "version": PIPELINE_VERSION},
        "created_at": created_at,
        "solver": spot_list["solver"],
        "spot_list_sha256": canonical_sha256(spot_list),
        "spots": manifest_spots,
    }
    if "list_id" in spot_list:
        manifest["list_id"] = spot_list["list_id"]
    files["manifest.json"] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
    return manifest, files


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("spot_list")
    ap.add_argument("--out", required=True, help="new batch folder (must not exist)")
    ap.add_argument("--dry-run", action="store_true", help="validate and print, write nothing")
    ap.add_argument("--solver-name", help="CSV input only")
    ap.add_argument("--solver-version", help="CSV input only")
    a = ap.parse_args(argv)
    try:
        spot_list = load_spot_list(a.spot_list, a.solver_name, a.solver_version)
    except SpotListError as e:
        print("[error] invalid spot list: %s" % e, file=sys.stderr)
        return 1
    created_at = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    manifest, files = build_batch(spot_list, created_at)
    print("[ok] spot list valid: %d spot(s), solver %s %s, spot_list_sha256=%s" % (
        len(spot_list["spots"]), spot_list["solver"]["name"], spot_list["solver"]["version"],
        manifest["spot_list_sha256"]))
    if os.path.exists(a.out):
        print("[error] output folder already exists, refusing to overwrite: %s" % a.out, file=sys.stderr)
        return 1
    if a.dry_run:
        print("[dry-run] would create %s with %d file(s):" % (a.out, len(files)))
        for rel in sorted(files):
            print("  %s  (%d bytes, sha256 %s)" % (rel, len(files[rel]), sha256_hex(files[rel])))
        for ms in manifest["spots"]:
            print("\n----- %s (street=%s, accuracy_target=%s%% of pot) -----" % (
                ms["input_file"], ms["spot"]["street"], ms["spot"]["accuracy_target"]))
            print(files[ms["input_file"]].decode("utf-8"), end="")
        print("\n[dry-run] nothing written.")
        return 0
    os.makedirs(a.out)
    for rel in sorted(files):
        p = os.path.join(a.out, *rel.split("/"))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "xb") as f:  # 'x' = fail rather than overwrite
            f.write(files[rel])
    print("[ok] wrote %d file(s) to %s" % (len(files), a.out))
    print("[next] Windows: run_all.bat <console_solver.exe> <resources dir>   then: python3 extract_pack.py %s --out PACK.json" % a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
